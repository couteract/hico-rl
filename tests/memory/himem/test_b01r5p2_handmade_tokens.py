def test_handmade_valid_decision0_accepted():
    """Handmade decision 0 token with correct layout should be accepted."""
    schema = TokenSchema()

    # Create properly formatted decision 0 token
    token_input = torch.zeros(schema.token_dim)

    # Set non-zero values only for visual_feature, state, and event_observable
    token_input[:schema.visual_feature_dim] = torch.randn(schema.visual_feature_dim)
    offset = schema.visual_feature_dim
    token_input[offset:offset + schema.state_dim] = torch.randn(schema.state_dim)

    # event_observable is at the end
    offset = (schema.visual_feature_dim + schema.state_dim + schema.action_summary_dim +
              1 + schema.visual_delta_dim + schema.state_delta_dim)
    token_input[offset:] = torch.randn(schema.event_observable_dim)

    metadata = {
        "env_id": "test",
        "episode_id": "ep1",
        "decision_index": 0,
        "decision_start_frame": 0,
        "prev_executed_start": None,
        "prev_executed_end": None,
        "prev_executed_count": None,
        "end_reason": None,
        "schema_version": HIMEM_SCHEMA_VERSION,
        "schema_hash": schema.compute_hash(),
    }

    token = CausalToken(model_input=token_input, audit_metadata=metadata)
    token.validate(schema)  # Should not raise


