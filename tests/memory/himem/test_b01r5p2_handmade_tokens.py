"""
B01R5P2: Handmade Token Layout Validation Tests

Tests that CausalToken.validate enforces layout constraints on handmade tokens,
not just tokens generated by EventFeatureEncoder.
"""

import pytest
import torch
from lerobot.memory.himem.config import TokenSchema, CausalToken, HIMEM_SCHEMA_VERSION


def test_handmade_decision0_with_nonzero_action_summary_rejected():
    """Handmade decision 0 token with non-zero action_summary must be rejected."""
    schema = TokenSchema()

    # Create a handmade token with non-zero action_summary
    token_input = torch.randn(schema.token_dim)

    # Manually set action_summary portion to non-zero
    offset = schema.visual_feature_dim + schema.state_dim
    token_input[offset:offset + schema.action_summary_dim] = torch.ones(schema.action_summary_dim)

    metadata = {
        "env_id": "test",
        "episode_id": "ep1",
        "decision_index": 0,
        "decision_start_frame": 0,
        "prev_executed_start": None,
        "prev_executed_end": None,
        "prev_executed_count": None,
        "end_reason": None,
        "schema_version": HIMEM_SCHEMA_VERSION,
        "schema_hash": schema.compute_hash(),
    }

    token = CausalToken(model_input=token_input, audit_metadata=metadata)

    with pytest.raises(ValueError, match="Decision 0 must have exact zero action_summary"):
        token.validate(schema)


